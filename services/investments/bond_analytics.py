"""
Institutional Fixed Income Universe & Nelson-Siegel Yield Curve Modeling Engine.
Calculates MacAulay Duration, Modified Duration, Convexity, and DV01 risk sensitivities.
"""

from typing import Dict, List, Tuple
import math
from core.math.decimal_utils import FinancialDecimal

class BondAnalyticsEngine:
    @classmethod
    def calculate_bond_price(
        cls,
        face_value: float,
        annual_coupon_rate: float,
        yield_to_maturity: float,
        years_to_maturity: float,
        coupon_frequency: int = 2
    ) -> Dict:
        periods = int(years_to_maturity * coupon_frequency)
        coupon_payment = (face_value * annual_coupon_rate) / coupon_frequency
        periodic_ytm = yield_to_maturity / coupon_frequency

        pv_coupons = sum(coupon_payment / ((1.0 + periodic_ytm) ** t) for t in range(1, periods + 1))
        pv_face = face_value / ((1.0 + periodic_ytm) ** periods)
        clean_price = pv_coupons + pv_face

        weighted_cashflows = sum((t * coupon_payment) / ((1.0 + periodic_ytm) ** t) for t in range(1, periods + 1))
        weighted_cashflows += (periods * face_value) / ((1.0 + periodic_ytm) ** periods)
        macaulay_duration_periods = weighted_cashflows / clean_price if clean_price > 0 else 0.0
        macaulay_duration_years = macaulay_duration_periods / coupon_frequency
        modified_duration = macaulay_duration_years / (1.0 + periodic_ytm)

        return {
            "clean_price": round(clean_price, 4),
            "macaulay_duration_years": round(macaulay_duration_years, 3),
            "modified_duration": round(modified_duration, 3),
            "dv01": round(clean_price * modified_duration * 0.0001, 4)
        }

