class QuantitativeEconometricsEngine:
    """Computes econometric regressions, Bayesian asset allocations, and volatility models."""

    @staticmethod
    def calculate_garch11_volatility(
        returns: List[float],
        omega: float = 0.000002,
        alpha: float = 0.09,
        beta: float = 0.89
    ) -> List[float]:
        """Calculates GARCH(1,1) conditional volatility time series: sigma_t^2 = omega + alpha*r_{t-1}^2 + beta*sigma_{t-1}^2."""
        if not returns:
            return []
        
        long_term_var = omega / (1.0 - alpha - beta) if (alpha + beta) < 1.0 else 0.0004
        variances = [long_term_var]
        
        for idx in range(1, len(returns)):
            prev_ret = returns[idx - 1]
            prev_var = variances[-1]
            next_var = omega + alpha * (prev_ret ** 2) + beta * prev_var
            variances.append(next_var)
            
        return [math.sqrt(v) for v in variances]

    @staticmethod
    def calculate_expected_shortfall(
        losses: List[float],
        confidence_level: float = 0.95
    ) -> float:
        """Computes Expected Shortfall / Conditional Value at Risk (CVaR)."""
        if not losses:
            return 0.0
        sorted_losses = sorted(losses, reverse=True)
        cutoff_idx = max(1, int(len(sorted_losses) * (1.0 - confidence_level)))
        tail_losses = sorted_losses[:cutoff_idx]
        return sum(tail_losses) / len(tail_losses)

    @staticmethod
    def black_litterman_expected_returns(
        market_caps: Dict[str, float],
        covariance_matrix: Dict[str, Dict[str, float]],
        risk_aversion: float = 2.5,
        investor_views: Optional[Dict[str, float]] = None
    ) -> Dict[str, float]:
        """Calculates Black-Litterman equilibrium implied returns blended with subjective investor views."""
        total_cap = sum(market_caps.values()) or 1.0
        weights = {sym: cap / total_cap for sym, cap in market_caps.items()}
        
        implied_returns = {}
        for sym_i, w_i in weights.items():
            ret = 0.0
            for sym_j, w_j in weights.items():
                cov = covariance_matrix.get(sym_i, {}).get(sym_j, 0.0004 if sym_i == sym_j else 0.0001)
                ret += risk_aversion * cov * w_j
            implied_returns[sym_i] = ret

        if not investor_views:
            return implied_returns

        # Blend views with implied prior
        blended = {}
        tau = 0.05
        for sym, prior_ret in implied_returns.items():
            view = investor_views.get(sym, prior_ret)
            blended[sym] = (prior_ret + tau * view) / (1.0 + tau)
        return blended
